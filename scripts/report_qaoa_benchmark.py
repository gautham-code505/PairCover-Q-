"""
Figures and markdown tables for the QAOA benchmark, noise study and in-loop run.

Usage:
    python scripts/report_qaoa_benchmark.py
"""

import json
import os
import sys
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(_ROOT, "reports", "qaoa_benchmark")
INK, PUR, PINK, GREY, RED, GRN = "#1b1530", "#7c4dff", "#ff7eb6", "#8a8799", "#e5484d", "#1a9e6b"
PCOL = {1: PINK, 2: "#a97bff", 3: PUR}


def load(name):
    path = os.path.join(OUT, name)
    return json.load(open(path, encoding="utf-8")) if os.path.exists(path) else None


def by(rows, *keys):
    out = defaultdict(list)
    for r in rows:
        out[tuple(r[k] for k in keys)].append(r)
    return out


def fig_enhancement(rows, path):
    """P(opt) relative to the uniform-feasible baseline, per instance, ramp chain vs random starts."""
    tight = [r for r in rows if r["penalty_factor"] == 1.0]
    ids = sorted({r["id"] for r in tight}, key=lambda i: (int(i.split("-")[1][:-1]), i))
    fig, ax = plt.subplots(figsize=(13, 4.6))
    x = np.arange(len(ids))
    for k, p in enumerate((1, 2, 3)):
        ramp = [next(r for r in tight if r["id"] == i and r["p"] == p and r["init"] == "ramp") for i in ids]
        rand = [[r for r in tight if r["id"] == i and r["p"] == p and r["init"] == "random"] for i in ids]
        off = (k - 1) * 0.25
        ax.scatter(x + off, [r["p_opt"] / r["random_feasible_p_opt"] for r in ramp], color=PCOL[p], s=46, zorder=3,
                   label=f"p = {p}, ramp + INTERP start")
        med = [np.median([r["p_opt"] / r["random_feasible_p_opt"] for r in rr]) for rr in rand]
        lo = [np.percentile([r["p_opt"] / r["random_feasible_p_opt"] for r in rr], 25) for rr in rand]
        hi = [np.percentile([r["p_opt"] / r["random_feasible_p_opt"] for r in rr], 75) for rr in rand]
        ax.errorbar(x + off, med, yerr=[np.subtract(med, lo), np.subtract(hi, med)], fmt="_", color=PCOL[p], alpha=.55,
                    capsize=2, label=f"p = {p}, 20 random starts (median, IQR)")
    ref = [next(r for r in tight if r["id"] == i)["random_p_opt"] / next(r for r in tight if r["id"] == i)["random_feasible_p_opt"] for i in ids]
    ax.plot(x, ref, color=GREY, ls=":", marker="", label="uniform over all bitstrings")
    ax.axhline(1, color=RED, ls="--", lw=1.4, label="uniform over feasible assignments")
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels(ids, rotation=40, ha="right", fontsize=8.5)
    ax.set_ylabel("P(exact optimum) / P under uniform-feasible")
    ax.set_title("QAOA probability of the exact optimum, relative to guessing uniformly among valid assignments "
                 "(above the red line = better)", fontsize=11, loc="left")
    ax.legend(fontsize=8, ncol=3, frameon=False, loc="lower left")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=170)
    plt.close(fig)


def fig_noise(noise, path):
    rows = noise["rows"]
    fig, axs = plt.subplots(1, 2, figsize=(12, 4.3))
    for ax, key, title in [(axs[0], "noisy", "all-to-all connectivity"),
                           (axs[1], "noisy_heavy_hex_equiv", "heavy-hex equivalent (approximation)")]:
        for r in rows:
            if r["p"] != 2:
                continue
            e2 = [x["e2"] * 100 for x in r[key]]
            ratio = [x["p_opt"] / r["random_feasible_p_opt"] for x in r[key]]
            col = plt.cm.plasma(min(r["qubits"], 12) / 13)
            ax.plot(e2, ratio, "-o", color=col, ms=4, label=f"{r['id']}")
        ax.axhline(1, color=RED, ls="--", lw=1.3)
        ax.set_yscale("log")
        ax.set_xlabel("two-qubit gate error (%)")
        ax.set_title(f"p = 2, {title}", fontsize=11, loc="left")
        ax.spines[["top", "right"]].set_visible(False)
    axs[0].set_ylabel("P(exact optimum) / uniform-feasible")
    axs[1].legend(fontsize=7, frameon=False, ncol=2)
    fig.tight_layout()
    fig.savefig(path, dpi=170)
    plt.close(fig)


def tables(res, noise, loop):
    rows = res["rows"]
    L = ["<!-- generated by scripts/report_qaoa_benchmark.py; do not edit by hand -->",
         f"All QAOA numbers are exact output probabilities of the optimised circuit (noiseless statevector). "
         f"'Hit in {res['shots']} shots' is 1 - (1 - P)^{res['shots']}.\n",
         "#### Per instance, tight penalty, ramp + INTERP chain\n",
         "| Instance | Qubits | Feasible / all | Coverage changes the answer | p | P(opt) QAOA | P(opt) uniform-all | P(opt) uniform-feasible | "
         "P(feasible) QAOA | P(feasible) uniform | Most likely string optimal | Evaluations |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted([r for r in rows if r["init"] == "ramp" and r["penalty_factor"] == 1.0],
                    key=lambda r: (r["qubits"], r["id"], r["p"])):
        L.append(f"| {r['id']} | {r['qubits']} | {r['n_feasible']} / {2 ** r['qubits']} | {'yes' if r['coverage_changes_answer'] else 'no'} | "
                 f"{r['p']} | {r['p_opt']*100:.2f}% | {r['random_p_opt']*100:.3f}% | {r['random_feasible_p_opt']*100:.2f}% | "
                 f"{r['p_feasible']*100:.1f}% | {r['random_p_feasible']*100:.1f}% | {'yes' if r['argmax_is_optimal'] else 'no'} | {r['nfev']} |")
    L += ["\n#### Summary by size (tight penalty)\n",
          "| Qubits | Instances | p | Ramp: median P(opt) / uniform-feasible | Ramp: beats uniform-feasible | "
          "Random starts: median P(opt) / uniform-feasible | Random starts: share beating uniform-feasible | Ramp: median P(feasible) |",
          "|---|---|---|---|---|---|---|---|"]
    tight = [r for r in rows if r["penalty_factor"] == 1.0]
    for (q, p), rr in sorted(by(tight, "qubits", "p").items()):
        ramp = [r for r in rr if r["init"] == "ramp"]
        rand = [r for r in rr if r["init"] == "random"]
        f = lambda r: r["p_opt"] / r["random_feasible_p_opt"]
        L.append(f"| {q} | {len(ramp)} | {p} | {np.median([f(r) for r in ramp]):.2f}x | {sum(f(r) > 1 for r in ramp)}/{len(ramp)} | "
                 f"{np.median([f(r) for r in rand]):.2f}x | {np.mean([f(r) > 1 for r in rand])*100:.0f}% | "
                 f"{np.median([r['p_feasible'] for r in ramp])*100:.0f}% |")
    L += ["\n#### Penalty sweep (ramp chain, p = 3): median over instances\n",
          "| Penalty factor | Median P(opt) / uniform-feasible | Median P(feasible) | Beats uniform-feasible |", "|---|---|---|---|"]
    for (fac,), rr in sorted(by([r for r in rows if r["init"] == "ramp" and r["p"] == 3], "penalty_factor").items()):
        f = [r["p_opt"] / r["random_feasible_p_opt"] for r in rr]
        L.append(f"| {fac:g}x | {np.median(f):.2f}x | {np.median([r['p_feasible'] for r in rr])*100:.0f}% | {sum(v > 1 for v in f)}/{len(f)} |")
    if noise:
        L += ["\n#### Noise and routing (ramp angles, tight penalty)\n",
              "| Instance | Qubits | p | 2q gates all-to-all | 2q gates heavy-hex | Routing factor | P(opt) ideal | "
              + " | ".join(f"P(opt) e2={x[0]*100:g}%" for x in noise["config"]["levels"][1:]) + " | "
              + " | ".join(f"heavy-hex equiv e2={x[0]*100:g}%" for x in noise["config"]["levels"][1:]) + " | uniform-feasible |",
              "|" + "---|" * (8 + 2 * (len(noise["config"]["levels"]) - 1))]
        for r in noise["rows"]:
            L.append(f"| {r['id']} | {r['qubits']} | {r['p']} | {r['all_to_all_2q']} | {r['heavy_hex_2q']} | {r['routing_ratio']:.1f}x | "
                     f"{r['ideal_p_opt']*100:.2f}% | " + " | ".join(f"{x['p_opt']*100:.2f}%" for x in r["noisy"][1:]) + " | "
                     + " | ".join(f"{x['p_opt']*100:.2f}%" for x in r["noisy_heavy_hex_equiv"][1:]) + f" | {r['random_feasible_p_opt']*100:.2f}% |")
    if loop:
        L += ["\n#### QAOA in the loop (PairCover-Q, lambda = 5, p = 2, 1024 shots per decision)\n",
              "| Load | Rep | Decisions | Trivial (≤ 1 qubit) | QAOA runs | QAOA best-of-shots = optimum | Fallback to exact | "
              "Most likely string = optimum | Uniform-random best-of-shots = optimum | Mean P(opt) QAOA vs uniform | Mean response QAOA / exact (min) |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for load, reps in loop["loads"].items():
            for i, r in enumerate(reps):
                s = r["stats"]
                L.append(f"| {load} | {i} | {s['decisions']} | {s['trivial']} | {s['qaoa_runs']} | {s['qaoa_agrees']}/{s['qaoa_runs']} | "
                         f"{s['qaoa_fallback']} | {s['argmax_agrees']}/{s['qaoa_runs']} | {s['random_agrees']}/{s['qaoa_runs']} | "
                         f"{(r['mean_p_opt'] or 0)*100:.0f}% vs {(r['mean_random_p_opt'] or 0)*100:.0f}% | "
                         f"{r['qaoa']['mean_response']:.2f} / {r['exact']['mean_response']:.2f} |")
    return "\n".join(L) + "\n"


def main():
    res = load("results.json")
    noise = load("noise_results.json")
    loop = load("in_loop_results.json")
    fig_enhancement(res["rows"], os.path.join(OUT, "fig_qaoa_vs_random.png"))
    if noise:
        fig_noise(noise, os.path.join(OUT, "fig_noise.png"))
    with open(os.path.join(OUT, "tables.md"), "w", encoding="utf-8") as f:
        f.write(tables(res, noise, loop))
    print("wrote figures and tables to", OUT)


if __name__ == "__main__":
    main()
